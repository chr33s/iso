#!/usr/bin/env python3
"""Regenerate Sources/IsoHost/Guest/EmbeddedResources.swift from scripts/guest/,
and Sources/IsoHost/Inference/EmbeddedInference.swift from the inference
gateway's and managed backend's resources in Sources/IsoHost/Inference/Resources/.

The Swift host embeds these files in the binary so it needs no resource files
at run time. `EmbeddedResourcesTests` and `embeddedInferenceResourcesMatchTheirFiles`
fail when a generated file is stale.

    python3 scripts/generate-embedded-resources.py [--check]
"""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = sorted(p for p in (ROOT / "scripts" / "guest").rglob("*") if p.is_file())
OUT = ROOT / "Sources" / "IsoHost" / "Guest" / "EmbeddedResources.swift"
INFERENCE = ROOT / "Sources" / "IsoHost" / "Inference"
INFERENCE_OUT = INFERENCE / "EmbeddedInference.swift"
# (Swift name, resource file, doc line)
INFERENCE_RESOURCES = [
    ("gatewayProfile", "seatbelt-inference.sb",
     "The `iso-inference` broker's Seatbelt profile (`SeatbeltProfile.inference`)."),
    ("workerProfile", "seatbelt-inference-worker.sb",
     "A session worker's Seatbelt profile; `SeatbeltProfile.inferenceWorker(backendPorts:)` renders its port rules."),
    ("launcher", "inference-launcher.py",
     "The managed mlx-lm backend's launcher, installed by `iso inference provision`."),
    ("backendProfile", "seatbelt-inference-backend.sb",
     "The managed backend's Seatbelt profile, installed by `iso inference provision`."),
    ("mlxLMLock", "mlx-lm-0.31.3.lock",
     "The hash-locked requirements `install` provisions for mlx-lm 0.31.3 (`scripts/lock-mlx-lm.py`)."),
]


def literal(text):
    hashes = "#"
    # Grow the delimiter until neither a closing quote nor an escape or
    # interpolation (`\#(`) with it can occur in the text.
    while f'"{hashes}' in text or f"\\{hashes}" in text:
        hashes += "#"
    # A multi-line literal drops the newline before its closing delimiter,
    # so add one to keep the file's final newline. Swift strips the closing
    # delimiter's indentation from every line, so indent the body to match
    # `swift format` (blank lines stay empty).
    body = "\n".join(f"    {line}" if line else "" for line in text.split("\n"))
    return f'{hashes}"""\n{body}\n    """{hashes}'


def guest_scripts():
    lines = [
        "// Derived from trailofbits/coop.",
        "// Modified by chr33s: ported/adapted for the Swift implementation.",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by scripts/generate-embedded-resources.py; do not edit.",
        "",
        "/// Guest scripts embedded in the binary, keyed by their path under",
        "/// `scripts/guest/`.",
        "package enum EmbeddedResources {",
        "  package static let guestScripts: [String: String] = [",
    ]
    for path in SOURCES:
        key = path.relative_to(ROOT / "scripts" / "guest").as_posix()
        text = path.read_text(encoding="utf-8")
        lines.append(f'    "{key}": {literal(text)},')
    lines += ["  ]", "", "  package static func guestScript(_ path: String) -> String { guestScripts[path]! }", "}", ""]
    return "\n".join(lines)


def inference_resources():
    lines = [
        "// Generated by scripts/generate-embedded-resources.py; do not edit.",
        "",
        "/// The inference gateway's and managed backend's resources, byte-identical",
        "/// to `Sources/IsoHost/Inference/Resources/` (the test scripts use those files).",
        "enum EmbeddedInference {",
    ]
    for index, (name, file, doc) in enumerate(INFERENCE_RESOURCES):
        text = (INFERENCE / "Resources" / file).read_text(encoding="utf-8")
        if index:
            lines.append("")
        lines.append(f"  /// {doc}")
        lines.append(f"  static let {name} = {literal(text)}")
    lines += ["}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the embedded files are stale")
    args = parser.parse_args()
    for out, content, what in [
        (OUT, guest_scripts(), f"{len(SOURCES)} scripts"),
        (INFERENCE_OUT, inference_resources(), f"{len(INFERENCE_RESOURCES)} resources"),
    ]:
        if args.check:
            if not out.exists() or out.read_text(encoding="utf-8") != content:
                raise SystemExit(f"stale {out.relative_to(ROOT)}; run scripts/generate-embedded-resources.py")
            print(f"verified {out.relative_to(ROOT)} ({what})")
        else:
            out.write_text(content, encoding="utf-8")
            print(f"wrote {out.relative_to(ROOT)} ({what})")


if __name__ == "__main__":
    main()
