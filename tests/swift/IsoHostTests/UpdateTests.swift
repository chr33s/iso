@Test func checksumsParseLikeSha256sum() throws {
  let b = String(repeating: "b", count: 64)
  #expect(
    Checksums.parse(
      "\(String(repeating: "a", count: 64))  other.tar.gz\n\(b)  iso-v1.tar.gz\n",
      file: "iso-v1.tar.gz")?.rawValue == b)
  let c = String(repeating: "c", count: 64)
  #expect(Checksums.parse("\(c) *iso.tar.gz\n", file: "iso.tar.gz")?.rawValue == c)
  let d = String(repeating: "d", count: 64)
  #expect(
    Checksums.parse("\n# generated by release.yml\n\(d)  x.tar.gz\n", file: "x.tar.gz")?.rawValue
      == d)
  #expect(
    Checksums.parse("\(String(repeating: "e", count: 64))  other.tar.gz\n", file: "iso.tar.gz")
      == nil)
  #expect(Checksums.parse("abcd  x.tar.gz\n", file: "x.tar.gz") == nil)
  #expect(
    Checksums.parse("\(String(repeating: "z", count: 64))  x.tar.gz\n", file: "x.tar.gz") == nil)
  let one = String(repeating: "1", count: 64)
  #expect(
    Checksums.parse(
      "\(one)  x.tar.gz\n\(String(repeating: "2", count: 64))  x.tar.gz\n", file: "x.tar.gz")?
      .rawValue == one)
  let three = String(repeating: "3", count: 64)
  #expect(Checksums.parse("\(three)  x.tar.gz\r\n", file: "x.tar.gz")?.rawValue == three)
  // Upper-case digests compare equal to the computed lower-case digest.
  #expect(
    Checksums.parse("\(String(repeating: "A", count: 64))  x\n", file: "x")
      == (try SHA256Hex(String(repeating: "a", count: 64))))
}

@Test func semverOrderingMatchesTheRustCrate() throws {
  func v(_ text: String) throws -> SemanticVersion { try SemanticVersion(parsing: text) }
  #expect(try v("0.3.2") > v("0.3.1"))
  #expect(try v("0.4.0") > v("0.4.0-rc.1"))
  #expect(try v("0.4.0-rc.1") > v("0.3.2"))
  #expect(try v("1.0.0-alpha") < v("1.0.0-alpha.1"))
  #expect(try v("1.0.0-alpha.1") < v("1.0.0-alpha.beta"))
  #expect(try v("1.0.0-beta.2") < v("1.0.0-beta.11"))
  #expect(try v("1.0.0-rc.1") < v("1.0.0"))
  #expect(try v("1.0.0") < v("1.0.0+build"))
  #expect(try v("1.2.3-rc.1+b.5").description == "1.2.3-rc.1+b.5")
  for (bad, message) in [
    ("", "empty string, expected a semver version"),
    ("01.0.0", "invalid leading zero in major version number"),
    ("1.0", "unexpected end of input while parsing minor version number"),
    ("1.0.0-01", "invalid leading zero in pre-release identifier"),
    ("1.0.0-", "empty identifier segment in pre-release identifier"),
    ("1.0.0/x", "unexpected character '/' after patch version number"),
  ] {
    #expect(throws: SemanticVersion.ParseError(description: message)) { try v(bad) }
  }
}

