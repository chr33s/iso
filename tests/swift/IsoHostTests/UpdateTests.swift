final class DiagnosticsLog: Sendable {
  private let lines = Mutex<[String]>([])
  var all: [String] { lines.withLock { $0 } }
  var diagnostics: Diagnostics {
    Diagnostics(verbosity: 1) { line in
      let message = line.range(of: " iso: ").map { String(line[$0.upperBound...]) } ?? line
      self.lines.withLock { $0.append(message) }
    }
  }
  func contains(_ text: String) -> Bool { all.contains { $0.contains(text) } }
}

func temporaryDirectory(_ label: String) throws -> String {
  let path = FileManager.default.temporaryDirectory.appending(
    path: "iso-\(label)-\(UUID().uuidString)"
  ).path
  try FileManager.default.createDirectory(atPath: path, withIntermediateDirectories: true)
  // Canonical (`/private/var/...`) so expected paths match realpath.
  return URL(fileURLWithPath: path).resolvingSymlinksInPath().path
}

func writeUpdateFile(_ path: String, _ text: String, mode: Int = 0o644) throws {
  try FileManager.default.createDirectory(
    atPath: (path as NSString).deletingLastPathComponent, withIntermediateDirectories: true)
  try Data(text.utf8).write(to: URL(fileURLWithPath: path))
  chmod(path, mode_t(mode))
}

func readText(_ path: String) -> String? { try? String(contentsOfFile: path, encoding: .utf8) }

