// MARK: - End to end against stub tools

/// A release fixture served by a stub `curl` (and optionally a stub `gh`)
/// on a private PATH; the real network is never reached.
private struct UpdateFixture {
  let root: String
  var bin: String { root + "/bin" }
  var served: String { root + "/served" }
  var install: String { root + "/install" }
  var home: String { root + "/home" }
  var log: String { root + "/calls.log" }
  let tag: String
  let signingKey = Curve25519.Signing.PrivateKey()
  var directoryName: String { "iso-\(tag)-aarch64-apple-darwin" }
  var tarballName: String { directoryName + ".tar.gz" }

  static let curl = """
    #!/bin/sh
    printf 'curl' >>"$STUB_LOG"; for a in "$@"; do printf ' %s' "$a" >>"$STUB_LOG"; done; echo >>"$STUB_LOG"
    url=""; dest=""; stdin=0
    while [ $# -gt 0 ]; do
      case "$1" in
        -fsSL) ;;
        -H) shift; [ "$1" = "@-" ] && stdin=1 ;;
        -o) shift; dest="$1" ;;
        *) url="$1" ;;
      esac
      shift
    done
    [ "$stdin" = 1 ] && cat >>"$STUB_LOG.stdin"
    rest="${url#*://}"; rest="${rest#*/}"
    case "$rest" in repos/*) path="$FIXTURE/$rest" ;; *) path="$FIXTURE/${url##*/}" ;; esac
    [ -f "$path" ] || exit 22
    if [ -n "$dest" ]; then cp "$path" "$dest"; else cat "$path"; fi
    """

  static let gh = """
    #!/bin/sh
    printf 'gh' >>"$STUB_LOG"; for a in "$@"; do printf ' %s' "$a" >>"$STUB_LOG"; done; echo >>"$STUB_LOG"
    case "$1 $2" in
      "auth status") exit 1 ;;
      "attestation verify") exit "${GH_VERIFY_EXIT:-0}" ;;
    esac
    exit 2
    """

  init(withGh: Bool = false, tag: String = "v9.9.9") throws {
    self.tag = tag
    root = try temporaryDirectory("update")
    try writeUpdateFile(bin + "/curl", Self.curl, mode: 0o755)
    if withGh { try writeUpdateFile(bin + "/gh", Self.gh, mode: 0o755) }
    for (name, text) in [
      ("iso", "installed-iso"), ("iso-proxy", "installed-proxy"),
      ("iso-sandbox", "installed-runtime"), ("iso-egress", "installed-egress"),
    ] {
      try writeUpdateFile(install + "/" + name, text, mode: 0o755)
    }
    try FileManager.default.createDirectory(atPath: home, withIntermediateDirectories: true)
  }

  func remove() { try? FileManager.default.removeItem(atPath: root) }

  /// Pack `members` into the release archive and publish matching sums.
  func publish(
    _ members: [String: String], corruptSums: Bool = false, bundle: String? = nil,
    signature: FixtureSignature = .trusted, base: String = "http://fixture",
    nonRegular: (name: String, symlink: Bool)? = nil
  ) throws {
    let stage = root + "/stage"
    try? FileManager.default.removeItem(atPath: stage)
    for (name, text) in members {
      try writeUpdateFile(stage + "/" + directoryName + "/" + name, text, mode: 0o755)
    }
    if let nonRegular {
      let path = stage + "/" + directoryName + "/" + nonRegular.name
      try FileManager.default.removeItem(atPath: path)
      if nonRegular.symlink {
        try FileManager.default.createSymbolicLink(
          atPath: path,
          withDestinationPath: nonRegular.name == "iso-proxy" ? "iso-sandbox" : "iso-proxy")
      } else {
        try FileManager.default.createDirectory(atPath: path, withIntermediateDirectories: false)
      }
    }
    try FileManager.default.createDirectory(atPath: served, withIntermediateDirectories: true)
    let tar = Process()
    tar.executableURL = URL(fileURLWithPath: "/usr/bin/tar")
    tar.arguments = ["-czf", served + "/" + tarballName, "-C", stage, directoryName]
    tar.environment = ["COPYFILE_DISABLE": "1"]
    try tar.run()
    tar.waitUntilExit()
    let digest =
      corruptSums
      ? String(repeating: "a", count: 64)
      : Checksums.of(Array(try Data(contentsOf: URL(fileURLWithPath: served + "/" + tarballName))))
        .rawValue
    let sums = "\(digest)  \(tarballName)\n"
    try writeUpdateFile(served + "/SHA256SUMS", sums)
    var assets = [
      #"{"name": "\#(tarballName)", "browser_download_url": "\#(base)/\#(tarballName)"}"#,
      #"{"name": "SHA256SUMS", "browser_download_url": "\#(base)/SHA256SUMS"}"#,
    ]
    let signer: Curve25519.Signing.PrivateKey?
    switch signature {
    case .trusted: signer = signingKey
    case .untrusted: signer = Curve25519.Signing.PrivateKey()
    case .missing: signer = nil
    }
    if let signer {
      try writeUpdateFile(
        served + "/SHA256SUMS.sig", try sshSign(Array(sums.utf8), key: signer))
      assets.append(
        #"{"name": "SHA256SUMS.sig", "browser_download_url": "\#(base)/SHA256SUMS.sig"}"#)
    }
    if let bundle {
      try writeUpdateFile(served + "/attestations.jsonl", bundle)
      assets.append(
        #"{"name": "attestations.jsonl", "browser_download_url": "\#(base)/attestations.jsonl"}"#)
    }
    let json = #"{"tag_name": "\#(tag)", "assets": [\#(assets.joined(separator: ", "))]}"#
    try writeUpdateFile(served + "/repos/chr33s/iso/releases/latest", json)
    try writeUpdateFile(served + "/repos/chr33s/iso/releases/tags/\(tag)", json)
  }

  /// Serve `text` as SHA256SUMS, signed by the trusted fixture key.
  func serveSums(_ text: String) throws {
    try writeUpdateFile(served + "/SHA256SUMS", text)
    try writeUpdateFile(served + "/SHA256SUMS.sig", try sshSign(Array(text.utf8), key: signingKey))
  }

  func updater(
    _ extra: [String: String] = ["ISO_UPDATE_API_BASE_URL": "http://fixture"], log: DiagnosticsLog,
    confirm: @escaping @Sendable (String) throws -> Bool = { _ in false }
  ) -> Updater {
    var environment = ["PATH": bin + ":/usr/bin:/bin", "FIXTURE": served, "STUB_LOG": self.log]
    environment.merge(extra) { $1 }
    var updater = Updater(
      environment: environment, home: home, build: releaseBuild,
      currentExecutable: install + "/iso", diagnostics: log.diagnostics, confirm: confirm,
      now: { 1234 })
    updater.signers = [signerKey(signingKey)]
    return updater
  }

  var installed: [String: String] {
    Dictionary(
      uniqueKeysWithValues: ((try? FileManager.default.contentsOfDirectory(atPath: install)) ?? [])
        .map {
          ($0, readText(install + "/" + $0) ?? "")
        })
  }

  var calls: [String] { (readText(log) ?? "").split(separator: "\n").map(String.init) }
}

enum FixtureSignature { case trusted, untrusted, missing }

private let fullRelease = [
  "iso": "new-iso", "iso-proxy": "new-proxy", "iso-sandbox": "new-runtime",
  "iso-egress": "new-egress",
]
private let untouched = [
  "iso": "installed-iso", "iso-proxy": "installed-proxy", "iso-sandbox": "installed-runtime",
  "iso-egress": "installed-egress",
]

/// Serialized: these spawn many short-lived processes, and the process-wide
/// descriptor-leak check in HostTests tolerates only a little concurrency.
@Suite(.serialized) struct UpdateEndToEnd {
  @Test func updateReplacesAllFourBinariesAndRecordsTheTag() throws {
    let fixture = try UpdateFixture()
    defer { fixture.remove() }
    try fixture.publish(fullRelease)
    let log = DiagnosticsLog()
    try fixture.updater(log: log).run(.init(skipConfirm: true))
    #expect(fixture.installed == fullRelease)
    #expect(
      UpdateCheck.readState(home: fixture.home)
        == UpdateState(lastCheckedAt: 1234, latestKnownVersion: "v9.9.9"))
    #expect(log.contains("attestation verification is DISABLED"))
    #expect(log.contains("Downloading iso-v9.9.9-aarch64-apple-darwin.tar.gz"))
    #expect(log.contains("iso updated to 9.9.9"))
    #expect(
      fixture.calls == [
        "curl -fsSL -H Accept: application/vnd.github+json http://fixture/repos/chr33s/iso/releases/latest",
        "curl -fsSL http://fixture/\(fixture.tarballName) -o " + fixture.calls[1].components(
          separatedBy: " -o "
        ).last!,
        "curl -fsSL http://fixture/SHA256SUMS -o " + fixture.calls[2].components(
          separatedBy: " -o "
        ).last!,
        "curl -fsSL http://fixture/SHA256SUMS.sig -o " + fixture.calls[3].components(
          separatedBy: " -o "
        ).last!,
      ])
    #expect(fixture.calls[1].hasSuffix("/" + fixture.tarballName))
  }

  @Test func checksumMismatchLeavesEveryBinaryUntouched() throws {
