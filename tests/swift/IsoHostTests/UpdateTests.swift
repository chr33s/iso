    UpdateCheck.readState(home: home) == UpdateState(lastCheckedAt: 0, latestKnownVersion: "v9.9.9")
  )
  for bad in [
    "{", "[]", #"{"last_checked_at": -1}"#, #"{"last_checked_at": "1"}"#,
    #"{"latest_known_version": 3}"#,
  ] {
    try writeUpdateFile(path, bad)
    #expect(UpdateCheck.readState(home: home) == nil, "\(bad)")
  }
}

